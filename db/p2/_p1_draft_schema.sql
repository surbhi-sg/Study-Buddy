-- Do not treat this as the course schema. Types match docs/p2/naming_map.md.

CREATE TABLE IF NOT EXISTS student (
    student_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    email          TEXT NOT NULL UNIQUE,
    password_hash  TEXT NOT NULL,
    year           SMALLINT,
    branch         TEXT
);

CREATE TABLE IF NOT EXISTS subject (
    subject_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS student_subject (
    student_id   INTEGER NOT NULL REFERENCES student (student_id),
    subject_id   INTEGER NOT NULL REFERENCES subject (subject_id),
    skill_level  SMALLINT NOT NULL CHECK (skill_level BETWEEN 1 AND 5),
    PRIMARY KEY (student_id, subject_id)
);

CREATE TABLE IF NOT EXISTS availability (
    student_id       INTEGER NOT NULL REFERENCES student (student_id),
    day_of_week      SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time       TIME NOT NULL,
    end_time         TIME NOT NULL,
    mode_preference  TEXT NOT NULL CHECK (mode_preference IN ('online', 'library')),
    CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS study_group (
    group_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_id  INTEGER NOT NULL REFERENCES subject (subject_id),
    mode        TEXT NOT NULL CHECK (mode IN ('online', 'library')),
    max_size    INTEGER NOT NULL CHECK (max_size >= 2),
    created_by  INTEGER NOT NULL REFERENCES student (student_id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS membership (
    student_id  INTEGER NOT NULL REFERENCES student (student_id),
    group_id    INTEGER NOT NULL REFERENCES study_group (group_id),
    role        TEXT NOT NULL CHECK (role IN ('admin', 'member')),
    joined_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (student_id, group_id)
);

CREATE TABLE IF NOT EXISTS session (
    session_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id          INTEGER NOT NULL REFERENCES study_group (group_id),
    start_datetime    TIMESTAMPTZ NOT NULL,
    duration          INTERVAL NOT NULL,
    location_or_link  TEXT
);

CREATE TABLE IF NOT EXISTS attendance (
    session_id  INTEGER NOT NULL REFERENCES session (session_id),
    student_id  INTEGER NOT NULL REFERENCES student (student_id),
    status      TEXT NOT NULL CHECK (status IN ('present', 'absent', 'excused')),
    PRIMARY KEY (session_id, student_id)
);

CREATE TABLE IF NOT EXISTS feedback (
    session_id  INTEGER NOT NULL REFERENCES session (session_id),
    student_id  INTEGER NOT NULL REFERENCES student (student_id),
    rating      SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment     TEXT,
    PRIMARY KEY (session_id, student_id)
);
